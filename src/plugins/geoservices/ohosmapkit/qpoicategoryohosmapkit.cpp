CategoryId tryGetCategoryId(const QString &categoryName)
{
    bool ok;
    auto categoryId =
        QMetaEnum::fromType<CategoryId>().keyToValue(
            categoryName.toLatin1().constData(), &ok);
    return ok ? static_cast<CategoryId>(categoryId) : CategoryId::INVALID;
}

