QString tryGetParentCategoryIdOrEmpty(const QString &categoryId)
{
    auto enumCategoryId = OhosPoiInternal::tryGetCategoryId(categoryId);
    if (enumCategoryId == OhosPoiInternal::CategoryId::INVALID)
        return QString();

    OhosPoiInternal::CategoryId parentId = OhosPoiInternal::CategoryId::INVALID;

    for (const auto &parentChildHierarchy : OhosPoiInternal::allParentChildHierarchies)
        if (parentChildHierarchy.contains(enumCategoryId))
            parentId = parentChildHierarchy.value(enumCategoryId);

    return parentId != OhosPoiInternal::CategoryId::INVALID
        ? OhosPoiInternal::getCategoryIdName(parentId)
        : QString();
}

QStringList tryGetChildCategoryIdsOrEmpty(const QString &categoryId)
{
    auto enumCategoryId = OhosPoiInternal::tryGetCategoryId(categoryId);
    if (enumCategoryId == OhosPoiInternal::CategoryId::INVALID)
        return QStringList();

    QStringList childCategoryIds;

    for (const auto &parentChildHierarchy : OhosPoiInternal::allParentChildHierarchies) {
        if (parentChildHierarchy.contains(enumCategoryId)) {
            for (auto it = parentChildHierarchy.begin(); it != parentChildHierarchy.end(); ++it)
                if (it.value() == enumCategoryId)
                    childCategoryIds.push_back(OhosPoiInternal::getCategoryIdName(it.key()));
            break;
        }
    }

    return childCategoryIds;
}

